import 'package:flowerpot/src/shared/media/upload_image.dart';
import 'package:flutter_test/flutter_test.dart';

/// 上传给花盆的图，宽高必须都是偶数（设备端 1.0.13 §1.1 #4：`w &= ~1; h &= ~1`）。
///
/// 为什么值得单独钉一条：奇数边不会报错，设备下载完**直接显示失败页**，
/// 手机这边一点提示都没有 —— 属于「改坏了没人知道」的那类缺陷。
/// 更新说明里给了两个实测案例，这里逐个复现。
void main() {
  (int, int) size(int w, int h) => UploadImage.targetSize(w, h);

  test('更新说明里的两个实测失败案例，现在都会被取成偶数', () {
    // 案例一：179 × 240 —— 在 320 × 240 的框**里面**，除了宽是奇数其余全合格，
    // 设备照样解不出来。所以取偶不能只在「超框缩放」那条路上做。
    expect(size(179, 240), (178, 240));

    // 案例二：9:16 竖图 1080 × 1920，等比缩进框得到 135 × 240，宽是奇数。
    expect(size(1080, 1920), (134, 240));
  });

  test('常见比例照旧，取偶不该把合规的图改小', () {
    // 4:3 正好贴满框，两边本来就是偶数。
    expect(size(1600, 1200), (320, 240));
    // 小图不放大（两边是偶数时一个像素都不动）。
    expect(size(200, 150), (200, 150));
  });

  // 这条钉的是缩放算式本身，不是取偶：原来「算一个 scale 再两边各乘」会被浮点咬，
  // 1920 × 0.16666666666666666 = 319.99999999999994，floor 之后是 319、高是 179 ——
  // 最常见的手机横拍照片反而两边都成了奇数，正是设备解不出来的那种图。
  test('16:9 横拍要正好落在 320 × 180，不能被浮点咬成 319 × 179', () {
    expect(size(1920, 1080), (320, 180));
    expect(size(3840, 2160), (320, 180));
  });

  test('奇数边一律削 1，不许四舍五入到更大', () {
    // 往上取会超出 320 × 240 这个硬框：321 × 241 先按高顶框，宽算出 319 再削成 318。
    expect(size(321, 241), (318, 240));
    expect(size(319, 239), (318, 238));
    expect(size(1, 1), (2, 2)); // 退化尺寸：取偶会变 0，兜到 2
  });

  test('非法尺寸原样返回，交给调用方当作处理失败', () {
    expect(size(0, 240), (0, 240));
    expect(size(-1, -1), (-1, -1));
  });
}
