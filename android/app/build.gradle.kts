import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.application")
    id("kotlin-android")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

val tuyaHomeSdkVersion = "7.5.1"
val tuyaExpansionSdkVersion = "7.8.0"

val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

val releaseSigningPropertyNames =
    listOf("storeFile", "keyAlias", "keyPassword", "storePassword")
val hasReleaseSigning =
    keystorePropertiesFile.exists() &&
        releaseSigningPropertyNames.all { !keystoreProperties.getProperty(it).isNullOrBlank() }
val aggregateArtifactTasks = setOf("assemble", "build", "bundle", "install", "package")
val buildsReleaseArtifact =
    gradle.startParameter.taskNames.any { taskName ->
        val simpleTaskName = taskName.substringAfterLast(':')
        simpleTaskName.contains("release", ignoreCase = true) ||
            aggregateArtifactTasks.any { simpleTaskName.equals(it, ignoreCase = true) }
    }

// Release must never fall back to the debug certificate: the Tuya security
// component is bound to the SHA-256 registered on the developer platform.
if (buildsReleaseArtifact && !hasReleaseSigning) {
    throw org.gradle.api.GradleException(
        "Release signing is not configured. Add storeFile, keyAlias, keyPassword, and " +
            "storePassword to ${keystorePropertiesFile.path} (see key.properties.example).",
    )
}

// Debug and profile still prefer the release certificate so the running app
// matches the fingerprint registered with Tuya. Without key.properties they
// fall back to Android's default debug keystore, which keeps `flutter run`
// working on an emulator for UI and mock-mode work.
if (!hasReleaseSigning) {
    logger.lifecycle(
        "[flowerpot] key.properties is missing or incomplete: debug/profile will use the " +
            "default Android debug keystore. Real Tuya calls need the certificate whose " +
            "SHA-256 is registered on the developer platform.",
    )
}

fun requiredKeystoreProperty(name: String): String =
    keystoreProperties.getProperty(name)
        ?: throw org.gradle.api.GradleException("Missing '$name' in ${keystorePropertiesFile.path}")

// The application-specific security AAR is generated by the Tuya Developer
// Platform and is never committed. Its presence is what switches the real SDK
// on, so it is resolved once here and reported at configuration time.
val tuyaSecurityAar = file("libs/security-algorithm.aar")
val tuyaSdkLinked = tuyaSecurityAar.exists()

val localProperties = Properties()
val localPropertiesFile = rootProject.file("local.properties")
if (localPropertiesFile.exists()) {
    localPropertiesFile.inputStream().use { localProperties.load(it) }
}
val tuyaAppKey = localProperties.getProperty("tuya.appKey", "").trim()
val tuyaAppSecret = localProperties.getProperty("tuya.appSecret", "").trim()

if (!tuyaSdkLinked) {
    logger.lifecycle(
        "[flowerpot] ${tuyaSecurityAar.path} is missing: building without the Tuya SDK. " +
            "The app still runs with the mock backend; --dart-define=TUYA_ENABLED=true will " +
            "report sdk_unavailable.",
    )
} else {
    if (tuyaAppKey.isEmpty() || tuyaAppSecret.isEmpty()) {
        logger.lifecycle(
            "[flowerpot] Tuya SDK is linked but tuya.appKey/tuya.appSecret are missing from " +
                "${localPropertiesFile.path}: the bridge will report credentials_missing.",
        )
    }
    logger.lifecycle(
        "[flowerpot] Tuya SDK enabled. Its native libraries ship armeabi-v7a and arm64-v8a " +
            "only, so real-mode runs need an emulator image with ARM translation (API 30+ " +
            "x86_64 or an arm64 image) or a physical device.",
    )
}

android {
    namespace = "com.common.yikaltd"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        applicationId = "com.common.yikaltd"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        // Flutter's current image picker and upcoming Flutter releases require 24.
        // This is also above Tuya SmartLife SDK 7.8.x's minimum requirement.
        minSdk = 24
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
        manifestPlaceholders["tuyaAppKey"] = tuyaAppKey
        manifestPlaceholders["tuyaAppSecret"] = tuyaAppSecret
    }

    packaging {
        jniLibs.pickFirsts += setOf(
            "lib/*/libc++_shared.so",
            "lib/*/liblog.so",
            "lib/*/libopenh264.so",
        )
    }

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                val releaseStoreFile = file(requiredKeystoreProperty("storeFile"))
                if (!releaseStoreFile.exists()) {
                    throw org.gradle.api.GradleException(
                        "Keystore file not found: ${releaseStoreFile.path}",
                    )
                }
                keyAlias = requiredKeystoreProperty("keyAlias")
                keyPassword = requiredKeystoreProperty("keyPassword")
                storeFile = releaseStoreFile
                storePassword = requiredKeystoreProperty("storePassword")
            }
        }
    }

    buildTypes {
        configureEach {
            if (hasReleaseSigning) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
        getByName("release") {
            // The Tuya bridge resolves SDK classes and callback interfaces
            // reflectively, so proguard-rules.pro must be wired in; without this
            // the file is never read and shrinking would strip com.thingclips.**.
            // Only the app rules are added: no optimization profile is enabled
            // here, so this stays additive to whatever Flutter configures.
            proguardFiles("proguard-rules.pro")
        }
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

configurations.all {
    exclude(group = "com.thingclips.smart", module = "thingplugin-annotation")
    exclude(group = "com.thingclips.android.module", module = "thingmodule-annotation")
    exclude(group = "com.thingclips.smart", module = "thingsmart-modularCampAnno")
}

dependencies {
    // Keeping the SDK conditional allows the repository to build before
    // credentials arrive; dropping the AAR into app/libs enables the real SDK.
    if (tuyaSdkLinked) {
        implementation(files(tuyaSecurityAar))
        implementation("com.thingclips.smart:thingsmart:$tuyaHomeSdkVersion")
        implementation("com.thingclips.smart:thingsmart-expansion-sdk:$tuyaExpansionSdkVersion")
        implementation("com.alibaba:fastjson:1.1.67.android")
        implementation("com.squareup.okhttp3:okhttp-urlconnection:3.14.9")
    }
}

flutter {
    source = "../.."
}
